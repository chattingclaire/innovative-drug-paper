h1('3 理论基础与分析框架')
h2('3.1 核心概念与理论逻辑')
p('曾润喜和莫敏丽（2023）{r31}将政府注意力界定为政府治理资源对某一议题或某一类事务的集中关注和指向，并将政策文本列为测量政府'
  '注意力的三条路径之一。注意力配置（又称注意力分配）描述注意力在不同议题之间的分布：文宏（2014）{r28}以关键词在中央政府工作报告'
  '中出现的频率测量政府对基本公共服务的注意力；练宏（2015）{lian2015}指出，注意力配置并不是个人技巧或计划安排意义上的技术问题，'
  '而是组织环境、制度环境和社会环境的产物。在此基础上，本文将注意力配置差异界定为不同部门在同一组评价维度之间配置注意力的结构性'
  '差别，以各评价维度注意力占比的部门间差异加以刻画。', first=True)
p('在宏观层面，Thornton和Ocasio（2008）{r25}的制度逻辑理论认为，不同制度场域中的行动者依据场域的核心原则发展出特定的认知模式与'
  '实践逻辑，这些逻辑界定了行动者的合法性标准和行为取向；Greenwood等（2011）{r26}进一步指出，组织同时面对多重制度逻辑要求时会'
  '产生制度复杂性。药监局、医保局、卫健委分别嵌入不同的制度逻辑，三种逻辑各有侧重，面对同一药品时可能得出不同判断，“三医协同”因而'
  '构成一个制度复杂性管理问题。')
p('在中观层面，Ocasio（1997）{r27}的注意力基础观认为，组织行为取决于决策者将注意力聚焦于哪些议题和答案，而注意力的配置受组织所处'
  '制度环境和规则结构的系统性约束。陶鹏和初春（2020）{r29}对府际领导批示的分析发现，核心议题对其他议题存在挤出效应，表明'
  '注意力基础观适用于中国政府组织。按照这一理论，不同制度逻辑会使三部门在审视同一药物时关注不同信息：药监局关注不良反应信号、临床'
  '试验数据与分子新颖性，医保局关注增量成本效果、预算影响与替代疗法，卫健委关注疾病负担、地区差异与基层配备。')
p('将两个层次联系起来，李梦颖等（2024）{r20}指出，制度逻辑决定着个人或组织注意力配置的基本原则，能帮助决策者把注意力集中在特定'
  '的问题和解决方案上。据此，本文的理论链条为：部门嵌入的制度逻辑决定其在评价维度之间的注意力配置，注意力配置体现为部门政策'
  '文本对各评价维度的关注程度，因而可以用政策文本中各评价维度的注意力占比测量三部门的注意力配置差异。')
p('以政策文本测量部门注意力配置有三方面依据。①正式文件与组织决策联系紧密，文本中关键词的词频统计可以作为组织及决策者关注重点的'
  '指示器（文宏 2014{r28}）。②组织注意力是稀缺资源（Cyert和March 1963{r23}），政策文本篇幅有限，何种议题被反复展开、何种议题'
  '仅简略提及，体现了部门在议题之间的取舍。③基于公开文本和公开词典的编码可由第三方复现，其结果能够与部门法定职能和专家访谈相互'
  '对照，而自动文本分析的结果须经验证方可采信（Grimmer和Stewart 2013{r33}）。政策文本反映的是制度层面的正式表达，与部门内个体'
  '决策者的关注仍有距离，这构成本文结论的适用边界。')

