def detailed_analyze_parta_data():
    """详细分析Part A基本信息数据"""
    print("正在详细分析Part A基本信息数据...")

    # 读取Part A数据
    df_parta = pd.read_csv('/Users/moonshot/Desktop/战略院/药企项目-创新药/调查问卷/02_提取的数据文件/排序后_PARTA_问卷数据.csv')

    # 数据清理
    df_parta = df_parta[df_parta['questionnaire_num'] <= 100]
    df_parta = df_parta[~df_parta['selected_option'].str.contains('  ', na=False)]
    df_parta = df_parta[~df_parta['selected_option'].str.contains('其他', na=False)]
    df_parta = df_parta[~df_parta['selected_option'].str.contains('Part B', na=False)]

    # 按问题分组分析
    questions = ['A1', 'A2', 'A3', 'A4']
    question_texts = {
        'A1': '您的职业是：',
        'A2': '您所在的机构类型：',
        'A3': '您从事创新药相关工作的年限：',
        'A4': '您参与药品监管、医疗保障、卫生健康管理等部门创新药相关评审/评价的经验：'
    }

    parta_results = {}

    for q in questions:
        q_data = df_parta[df_parta['question_num'] == q]
        option_counts = q_data['selected_option'].value_counts()
        total_responses = len(q_data)

        parta_results[q] = {
            'question_text': question_texts[q],
            'total_responses': total_responses,
            'option_counts': option_counts,
            'percentage': (option_counts / total_responses * 100).round(2)
        }

    return parta_results

def detailed_analyze_partb_data():
    """详细分析Part B维度重要性数据"""
    print("正在详细分析Part B维度重要性数据...")

    # 读取Part B数据
    df_partb = pd.read_csv('/Users/moonshot/Desktop/战略院/药企项目-创新药/调查问卷/02_提取的数据文件/排序后_PARTB_问卷数据.csv')

    # 数据清理
    df_partb = df_partb[df_partb['questionnaire_num'] <= 100]
    df_partb = df_partb[df_partb['choice'].astype(str).str.isdigit()]
    df_partb['choice'] = df_partb['choice'].astype(int)

    # 按维度分组分析
    dimensions = ['B1', 'B2', 'B3', 'B4', 'B5']
    dimension_names = {
        'B1': '安全维度',
        'B2': '有效维度',
        'B3': '经济维度',
        'B4': '创新维度',
        'B5': '公平维度'
    }

    partb_results = {}

    for d in dimensions:
        d_data = df_partb[df_partb['question_num'] == d]
        score_counts = d_data['choice'].value_counts().sort_index()
        total_responses = len(d_data)

        # 计算详细统计指标
        mean_score = d_data['choice'].mean()
        median_score = d_data['choice'].median()
        std_score = d_data['choice'].std()
        min_score = d_data['choice'].min()
        max_score = d_data['choice'].max()

        # 计算高分比例（5-6分）
        high_score_count = len(d_data[d_data['choice'] >= 5])
        high_score_ratio = high_score_count / total_responses * 100

        # 计算低分比例（1-3分）
        low_score_count = len(d_data[d_data['choice'] <= 3])
        low_score_ratio = low_score_count / total_responses * 100

        partb_results[d] = {
            'dimension_name': dimension_names[d],
            'total_responses': total_responses,
            'score_counts': score_counts,
            'percentage': (score_counts / total_responses * 100).round(2),
            'mean_score': round(mean_score, 2),
            'median_score': median_score,
            'std_score': round(std_score, 2),
            'min_score': min_score,
            'max_score': max_score,
            'high_score_ratio': round(high_score_ratio, 2),
            'low_score_ratio': round(low_score_ratio, 2)
        }

    return partb_results

def detailed_analyze_partb6_data():
    """详细分析Part B6排序题数据"""
    print("正在详细分析Part B6排序题数据...")

    # 读取Part B6数据
    df_partb6 = pd.read_csv('/Users/moonshot/Desktop/战略院/药企项目-创新药/调查问卷/02_提取的数据文件/排序后_PARTB6_问卷数据.csv')

    # 数据清理
    df_partb6 = df_partb6[df_partb6['questionnaire_num'] <= 100]

    # 按维度统计排序情况
    dimensions = ['安全维度', '有效维度', '经济维度', '创新维度', '公平维度']

    partb6_results = {}

    for dim in dimensions:
        dim_data = df_partb6[df_partb6['dimension'] == dim]
        rank_counts = dim_data['rank'].value_counts().sort_index()
        total_responses = len(dim_data)

        # 计算详细统计指标
        mean_rank = dim_data['rank'].mean()
        median_rank = dim_data['rank'].median()
        std_rank = dim_data['rank'].std()

        # 计算前两名比例
        top2_count = len(dim_data[dim_data['rank'] <= 2])
        top2_ratio = top2_count / total_responses * 100

        # 计算后两名比例
        bottom2_count = len(dim_data[dim_data['rank'] >= 4])
        bottom2_ratio = bottom2_count / total_responses * 100

        partb6_results[dim] = {
            'total_responses': total_responses,
            'rank_counts': rank_counts,
            'percentage': (rank_counts / total_responses * 100).round(2),
            'mean_rank': round(mean_rank, 2),
            'median_rank': median_rank,
            'std_rank': round(std_rank, 2),
            'top2_ratio': round(top2_ratio, 2),
            'bottom2_ratio': round(bottom2_ratio, 2)
        }

    return partb6_results

