# ---- 结论 ----
I[118] = "本文基于“制度逻辑—组织注意力”框架，综合运用政策文本编码、条文分析与访谈资料，考察创新药上市审评、医保准入与临床使用环节评价规则的差异及其对创新主体的影响，得出以下结论：第一，三部门评价规则的关注重点存在差异，药监局侧重安全性与有效性，医保局侧重经济性，卫健委安全性与经济性占比较高但排序受联合发文影响。创新药由此在不同环节面临以不同维度为核心的证据要求。第二，上述差异集中表现为比较基础、证据类型与应用条件三类证据断点，构成创新主体证据准备中的主要不确定性来源。第三，跨部门协同为创新提供的确定性，不在于统一评价标准或预先确定评审结果，而在于明确各环节的证据要求及既有证据的适用条件，使企业能够在研发阶段统筹规划后续证据。"
