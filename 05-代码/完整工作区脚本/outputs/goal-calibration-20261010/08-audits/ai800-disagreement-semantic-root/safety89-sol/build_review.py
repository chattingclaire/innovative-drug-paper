def manual_evidence(path):
    ls=MAN.read_text().splitlines()
    def part(start,stop):
        lo=next(i for i,l in enumerate(ls) if l.startswith(start))
        hi=next(i for i,l in enumerate(ls[lo+1:],lo+1) if l.startswith(stop))
        return {'file':str(MAN),'line_range_1based_inclusive':[lo+1,hi], 'quote':'\n'.join(ls[lo:hi])}
    # S定义、纳排、边界整节；共同条款只按当前路径摘录已经实际阅读的完整原段。
    out=[part('## 三、安全性 S','## 四、有效性 E')]
    if any(t in path for t in ['标准','总领','成员','条件','同版']):
        targets=['- 当前有“应包括下列”','- 当前直接要求药品符合确指条','- “详见工作方案”']
    elif any(t in path for t in ['证据','信息','方法','合规','递交','学科','栏目']):
        targets=['**概括性评价要求与具体机制分开。**','**资料与证据也用同一门槛。**']
    else:
        targets=['**五维使用同一实质门槛：**','4. **限定必要语境。**']
    for target in targets:
        i=next(i for i,l in enumerate(ls) if l.startswith(target))
        out.append({'file':str(MAN),'line_range_1based_inclusive':[i+1,i+1],'quote':ls[i]})
    return out

