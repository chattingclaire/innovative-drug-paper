def make_row(inp):
    rid = inp["id"]
    positives, isub, fsub, sbasis = J[rid]
    if positives == "P":
        issue = "该单元为缺少后续实质内容的引导语或孤立责任括注，无法确定完整对象与要求，需补充相邻完整条款。"
        return {
            "id": rid,
            "labels": {d: "待定" for d in DIMS},
            "dimension_reasons": {d: issue for d in DIMS},
            "evidence": [], "material_issue": issue,
            "fairness_subtypes": [], "innovation_subtypes": [],
            "safety_quality_basis": "undetermined",
        }
    pos = set(positives.split(",")) if positives else set()
    labels = {d: (1 if d in pos else 0) for d in DIMS}
    reasons = {}
    for d in DIMS:
        if d in pos:
            reasons[d] = f"原文实质涉及{DESC[d]}。"
        else:
            reasons[d] = f"该单元未实质讨论{DESC[d]}。"
    evidence = [{"dimension": d, "source": "unit", "quote": inp["text"]} for d in DIMS if d in pos]
    return {
        "id": rid, "labels": labels, "dimension_reasons": reasons,
        "evidence": evidence, "material_issue": "",
        "fairness_subtypes": fsub, "innovation_subtypes": isub,
        "safety_quality_basis": sbasis,
    }

def main():
    seen = []
    for n in range(1, 32):
        ip = HERE / f"input-{n:03d}.json"
        op = HERE / f"output-{n:03d}.json"
        inputs = json.loads(ip.read_text())["rows"]
        seen.extend(r["id"] for r in inputs)
        if op.exists():
            raise SystemExit(f"refusing to overwrite {op.name}")
        result = {"protocol_version": "CAL-5D-20260926-v1.3", "rows": [make_row(r) for r in inputs]}
        with op.open("x", encoding="utf-8") as fh:
            json.dump(result, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
    missing = set(seen) - set(J)
    extra = set(J) - set(seen)
    if missing or extra or len(seen) != 304:
        raise SystemExit(f"judgment coverage mismatch missing={missing} extra={extra} n={len(seen)}")

if __name__ == "__main__":
    main()
